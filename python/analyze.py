"""
Aerowind - KPI computation.

Reads data/processed/ (run clean.py first), computes the KPIs shown in the
dashboard and used in the report, writes docs/results.md and the charts in images/.

Usage:  python python/analyze.py
"""
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data" / "processed"
IMG = ROOT / "images"
DOCS = ROOT / "docs"

# Chart tokens (light surface, validated categorical slots 1-3)
SURFACE, INK, INK2, GRID = "#fcfcfb", "#0b0b0b", "#52514e", "#e4e3df"
S1, S2, S3, MUTED = "#2a78d6", "#eb6834", "#1baf7a", "#b9b8b3"
MODEL_COLOR = {"Vestas V100": S1, "Vestas V110": S2, "GE.2.5-116": S3}

plt.rcParams.update({
    "figure.facecolor": SURFACE, "axes.facecolor": SURFACE, "savefig.facecolor": SURFACE,
    "axes.edgecolor": GRID, "axes.labelcolor": INK2, "xtick.color": INK2, "ytick.color": INK2,
    "text.color": INK, "font.size": 11, "axes.spines.top": False, "axes.spines.right": False,
    "axes.grid": True, "grid.color": GRID, "grid.linewidth": 0.8, "axes.axisbelow": True,
})


def read(name, **kwargs):
    return pd.read_csv(DATA / name, sep=";", **kwargs)


def load():
    t = read("Turbines.csv", parse_dates=["installation_date"])
    p = read("Production.csv", parse_dates=["date"]).merge(
        t[["turbine_id", "model", "nominal_power_kw"]], on="turbine_id")
    m = read("Maintenance.csv", parse_dates=["maintenance_date"])
    w = read("Weather.csv", parse_dates=["date"])
    pr = read("Price.csv", parse_dates=["date"])
    p["y"] = p.date.dt.year
    p["month"] = p.date.dt.to_period("M")
    p["price"] = p.month.map(dict(zip(pr.date.dt.to_period("M"), pr.price_kwh_usd)))
    p["revenue_usd"] = p.generated_energy_kwh * p.price
    m["y"] = m.maintenance_date.dt.year
    return t, p, m, w


# Same definitions as the dashboard measures
def cf(d):
    return d.generated_energy_kwh.sum() / (d.nominal_power_kw * 24).sum()


def availability(d):
    return d.operating_hours.sum() / (d.operating_hours + d.inactive_hours).sum()


def performance(d, corrective):
    return round(0.65 * availability(d) + 0.30 * cf(d) + 0.05 * (1 / (1 + corrective)), 4)


def pct(x):
    return f"{x:.1%}"


def md_table(df):
    df = df.reset_index()
    head = "| " + " | ".join(map(str, df.columns)) + " |"
    sep = "|" + "|".join("---" for _ in df.columns) + "|"
    rows = ["| " + " | ".join(map(str, r)) + " |" for r in df.itertuples(index=False)]
    return "\n".join([head, sep, *rows])


def main():
    t, p, m, w = load()
    out = ["# Results\n", "_Generated by `python/analyze.py` from `data/processed/`. Do not edit by hand._\n"]
    corrective = m[m.maintenance_type == "Corrective"]

    # ---------------- Park KPIs by year ----------------
    cost = m.groupby("y").cost_usd.sum()
    yr = p.groupby("y").apply(lambda d: pd.Series({
        "turbines": d.turbine_id.nunique(),
        "energy_GWh": round(d.generated_energy_kwh.sum() / 1e6, 2),
        "capacity_factor": pct(cf(d)),
        "availability": pct(availability(d)),
        "performance": f"{performance(d, (corrective.y == d.name).sum()):.2%}",
        "revenue_USD": round(d.revenue_usd.sum()),
    }), include_groups=False)
    yr["maintenance_cost_USD"] = cost.round().astype(int)
    yr["profit_USD"] = (p.groupby("y").revenue_usd.sum() - cost).round().astype(int)
    yr["profit_growth"] = yr.profit_USD.pct_change().map(lambda x: "-" if pd.isna(x) else f"{x:+.1%}")
    out += ["## Park KPIs by year\n", md_table(yr.rename_axis("year")), ""]

    # ---------------- Technology ----------------
    by_model = p.groupby(["model", "y"]).apply(cf, include_groups=False).unstack()
    out += ["## Capacity factor by turbine model and year\n",
            md_table(by_model.map(lambda v: "-" if pd.isna(v) else pct(v)).rename_axis("model")), ""]
    wind = w.groupby(w.date.dt.year).wind_speed_mps.mean().round(2)
    out += ["Mean wind speed by year (m/s): " + ", ".join(f"{k}: {v}" for k, v in wind.items()), ""]
    av_model = p.groupby("model").apply(availability, include_groups=False)
    out += ["Availability by model (2023-2025): " + ", ".join(f"{k}: {pct(v)}" for k, v in av_model.items()), ""]
    first = m.merge(t[["turbine_id", "installation_date", "model"]], on="turbine_id")
    first = first[(first.maintenance_type == "Corrective") &
                  (first.maintenance_date < first.installation_date + pd.DateOffset(years=1))]
    fy = (first.groupby("model").size() / t.groupby("model").size()).fillna(0).round(1)
    out += ["Corrective events per turbine in its first year of operation: "
            + ", ".join(f"{k}: {v}" for k, v in fy.items()), ""]

    # ---------------- Turbine scorecard ----------------
    years = p.groupby("turbine_id").y.nunique()
    mt = m.groupby("turbine_id").agg(events=("cost_usd", "size"),
                                     corrective=("maintenance_type", lambda s: (s == "Corrective").sum()),
                                     cost=("cost_usd", "sum"))
    sc = p.groupby("turbine_id").apply(lambda d: pd.Series({
        "model": d.model.iloc[0], "years": d.y.nunique(),
        "capacity_factor": pct(cf(d)), "availability": pct(availability(d)),
    }), include_groups=False).join(mt)
    sc["corrective_per_year"] = (sc.corrective / years).round(1)
    sc["maint_cost_USD"] = sc.cost.round().astype(int)
    sc["maint_USD_per_MWh"] = (sc.cost / (p.groupby("turbine_id").generated_energy_kwh.sum() / 1e3)).round(2)
    avail_num = p.groupby("turbine_id").apply(availability, include_groups=False)
    r = np.corrcoef(sc.cost[avail_num.index], avail_num)[0, 1]
    out += ["## Turbine scorecard (2023-2025)\n", md_table(sc.drop(columns=["cost", "corrective"])), "",
            f"Correlation between total maintenance cost and availability across turbines: r = {r:.2f}", ""]

    # T003 vs the other V100 units at the same wind speed
    d = p.merge(w[["date", "wind_speed_mps"]], on="date").dropna(subset=["wind_speed_mps"])
    d = d[d.model == "Vestas V100"].assign(bin=lambda x: pd.cut(x.wind_speed_mps, [0, 4, 6, 8, 10, 15]),
                                           grp=lambda x: np.where(x.turbine_id == "T003", "T003", "other V100"))
    rp = d.groupby(["bin", "grp"], observed=True).apply(
        lambda x: x.generated_energy_kwh.sum() / x.operating_hours.sum(), include_groups=False).unstack().round(0)
    rp["T003_vs_other"] = (rp["T003"] / rp["other V100"] - 1).map(lambda x: f"{x:+.0%}")
    out += ["## Real power while operating (kW): T003 vs the other V100 units\n",
            md_table(rp.rename_axis("wind_speed_mps")), ""]

    # ---------------- Maintenance ----------------
    mix = m.pivot_table(index="y", columns="maintenance_type", values="cost_usd", aggfunc=["size", "sum"])
    mix.columns = [f"{'events' if a == 'size' else 'cost_USD'}_{b.lower()}" for a, b in mix.columns]
    out += ["## Maintenance by year and type\n", md_table(mix.round(0).astype(int).rename_axis("year")), "",
            "Average cost per event: " + ", ".join(f"{k}: USD {v:,.0f}"
                                                   for k, v in m.groupby("maintenance_type").cost_usd.mean().items()), ""]
    cat = corrective.groupby("category").agg(events=("cost_usd", "size"), cost_USD=("cost_usd", "sum"),
                                             avg_hours=("duration_hs", "mean")).sort_values("events", ascending=False)
    cat["cost_USD"] = cat.cost_USD.round().astype(int)
    cat["avg_hours"] = cat.avg_hours.round(1)
    out += ["## Corrective events by failure category\n", md_table(cat), ""]
    t003 = corrective[corrective.turbine_id == "T003"].category.value_counts()
    out += ["T003 corrective events by category: " + ", ".join(f"{k}: {v}" for k, v in t003.items()), ""]

    # ---------------- Seasonality and wind ----------------
    mon = p.groupby(p.date.dt.month).apply(cf, include_groups=False)
    prev = m[m.maintenance_type == "Preventive"]
    prev_m = prev.groupby(prev.maintenance_date.dt.month).size().reindex(range(1, 13), fill_value=0)
    high = mon[mon >= 0.30].index.tolist()
    out += ["## Seasonality\n",
            md_table(pd.DataFrame({"capacity_factor": mon.map(pct), "preventive_events": prev_m}).rename_axis("month")),
            "", f"High-wind months (CF >= 30%): {high}. Preventive events in those months: "
                f"{prev_m[high].sum()} of {prev_m.sum()} ({prev_m[high].sum() / prev_m.sum():.0%}).", ""]
    dw = p.merge(w[["date", "wind_speed_mps"]], on="date").dropna(subset=["wind_speed_mps"])
    share = dw.groupby(pd.cut(dw.wind_speed_mps, [0, 4, 6, 8, 10, 15]), observed=True).generated_energy_kwh.sum()
    out += ["Share of energy by daily mean wind speed (m/s): "
            + ", ".join(f"{k}: {v / share.sum():.0%}" for k, v in share.items()), ""]

    # ---------------- Monthly result ----------------
    mm = pd.DataFrame({"revenue": p.groupby("month").revenue_usd.sum(),
                       "maint_cost": m.groupby(m.maintenance_date.dt.to_period("M")).cost_usd.sum()}).fillna(0)
    neg = mm[mm.revenue - mm.maint_cost < 0]
    out += ["## Monthly revenue minus maintenance cost\n",
            f"Months with negative result: {len(neg)} "
            + ("(" + ", ".join(f"{i}: revenue USD {r.revenue:,.0f}, maintenance USD {r.maint_cost:,.0f}"
                               for i, r in neg.iterrows()) + ")" if len(neg) else ""), ""]

    (DOCS / "results.md").write_text("\n".join(out))
    print("\n".join(out))

    # ================= Charts =================
    IMG.mkdir(exist_ok=True)

    # 1) CF by model x year
    fig, ax = plt.subplots(figsize=(8, 4.2))
    models, yrs, bw = ["Vestas V100", "Vestas V110", "GE.2.5-116"], [2023, 2024, 2025], 0.26
    for i, mdl in enumerate(models):
        vals = [by_model.loc[mdl, y] if not pd.isna(by_model.loc[mdl, y]) else np.nan for y in yrs]
        xs = np.arange(3) + (i - 1) * bw
        ax.bar(xs, vals, width=bw - 0.03, color=MODEL_COLOR[mdl], label=mdl)
        for x, v in zip(xs, vals):
            if not np.isnan(v):
                ax.text(x, v + 0.006, f"{v:.0%}", ha="center", va="bottom", fontsize=9, color=INK2)
    ax.set_xticks(range(3), yrs)
    ax.yaxis.set_major_formatter(matplotlib.ticker.PercentFormatter(1, decimals=0))
    ax.set_ylim(0, 0.33)
    ax.grid(axis="x", visible=False)
    ax.set_title("Capacity factor by turbine model and year", loc="left", fontsize=11.5, color=INK)
    ax.legend(frameon=False, ncol=3, loc="upper left", fontsize=9.5)
    fig.tight_layout()
    fig.savefig(IMG / "cf_by_model_year.png", dpi=160)
    plt.close(fig)

    # 2) Seasonality vs preventive maintenance timing (two panels, shared x, no dual axis)
    fig, (a1, a2) = plt.subplots(2, 1, figsize=(8, 5), sharex=True, gridspec_kw={"height_ratios": [1.3, 1]})
    months = list(range(1, 13))
    labels = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]
    a1.plot(months, mon.values, color=S1, lw=2, marker="o", ms=5)
    a1.yaxis.set_major_formatter(matplotlib.ticker.PercentFormatter(1, decimals=0))
    a1.set_ylabel("Capacity factor")
    a1.axvspan(min(high) - 0.5, max(high) + 0.5, color=S1, alpha=0.07, lw=0)
    a1.set_ylim(0, mon.max() * 1.1)
    a1.text(min(high) - 0.35, 0.02, "high-wind season", fontsize=9, color=INK2, va="bottom")
    a2.bar(months, prev_m.values, color=[S2 if mo in high else MUTED for mo in months], width=0.62)
    a2.set_ylabel("Preventive jobs")
    a2.grid(axis="x", visible=False)
    a2.set_xticks(months, labels)
    a1.set_title("Monthly capacity factor and preventive maintenance jobs", loc="left", fontsize=11.5)
    fig.tight_layout()
    fig.savefig(IMG / "seasonality_maintenance.png", dpi=160)
    plt.close(fig)
    print("\nCharts written to images/")


if __name__ == "__main__":
    main()
